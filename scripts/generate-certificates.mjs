#!/usr/bin/env node
// Appends new rows from participant CSV(s) into src/data/certificates/index.ts.
//
//   bun run scripts/generate-certificates.mjs <input.csv> [<input2.csv> ...]
//
// Certificate identity is (templateId + normalized email). Existing entries are
// kept; only new template/email pairs are appended.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { normalizeEmail, parseCsv } from "./certificate-csv.mjs";
import { getTemplate } from "../src/data/certificates/templates/index.ts";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = `${ROOT}/src/data/certificates/index.ts`;

function rowToCert(row) {
  if (!getTemplate(row.templateId)) {
    throw new Error(`Unknown certificate template: ${row.templateId}`);
  }
  const email = normalizeEmail(row.email);
  return {
    email,
    name: row.name,
    eventSlug: row.eventSlug,
    templateId: row.templateId,
  };
}

async function loadExisting() {
  if (!existsSync(OUT)) return [];
  const { CERTIFICATES } = await import(pathToFileURL(OUT).href);
  return CERTIFICATES;
}

async function main() {
  const inputs = process.argv.slice(2);
  if (!inputs.length) {
    console.error(
      "usage: bun run scripts/generate-certificates.mjs <input.csv> [...]",
    );
    process.exit(1);
  }

  const existing = await loadExisting();
  const byKey = new Map(existing.map((c) => [`${c.templateId}|${c.email}`, c]));
  const before = byKey.size;

  for (const row of inputs.flatMap((f) => parseCsv(readFileSync(f, "utf8")))) {
    const cert = rowToCert(row);
    const key = `${cert.templateId}|${cert.email}`;
    if (!byKey.has(key)) byKey.set(key, cert);
  }

  const unique = [...byKey.values()];
  const added = unique.length - before;

  const body = `// AUTO-GENERATED by scripts/generate-certificates.mjs — do not edit by hand.
import type { Certificate } from "./types";

export const CERTIFICATES: Certificate[] = ${JSON.stringify(unique, null, 2)};

const normalizeEmail = (email: string): string => email.trim().toLowerCase();
const keyOf = (templateId: string, email: string): string => \`\${templateId}|\${normalizeEmail(email)}\`;

const BY_KEY = new Map(CERTIFICATES.map((c) => [keyOf(c.templateId, c.email), c]));

const BY_EMAIL = new Map<string, Certificate[]>();
for (const cert of CERTIFICATES) {
  const email = normalizeEmail(cert.email);
  BY_EMAIL.set(email, [...(BY_EMAIL.get(email) ?? []), cert]);
}

export const getCertificateByTemplateAndEmail = (templateId: string, email: string): Certificate | undefined =>
  BY_KEY.get(keyOf(templateId, email));

export const getCertificatesByEmail = (email: string): Certificate[] =>
  BY_EMAIL.get(normalizeEmail(email)) ?? [];

export const getCertificatePath = (templateId: string, email: string): string =>
  \`/cert?templateId=\${templateId}&email=\${normalizeEmail(email)}\`;

export type { Certificate } from "./types";
`;

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, body);
  console.log(
    `Wrote ${unique.length} certificate(s) (${added} added) -> ${OUT}`,
  );
}

main();
