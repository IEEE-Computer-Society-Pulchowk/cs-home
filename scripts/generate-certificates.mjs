#!/usr/bin/env node
// Generates src/data/certificates/index.ts from a participant CSV.
//
//   bun run scripts/generate-certificates.mjs <input.csv> [<input2.csv> ...]
//
// IDs are a pure function of (eventSlug, email) -> re-running is idempotent and
// never reassigns an already-issued ID. No write-back to the CSV.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import QRCode from "qrcode";

const SITE_URL = (process.env.SITE_URL || "https://ieeecs.pcampus.edu.np").replace(/\/$/, "");
const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = `${ROOT}/src/data/certificates/index.ts`;
const COLUMNS = ["name", "email", "event", "eventSlug", "issueYear", "date", "templateId"];

// ponytail: naive split — fine for a flat participant list with no embedded
// commas/quotes. Swap in `csv-parse` only if a real CSV breaks this.
function parseCsv(text) {
  const lines = text.replace(/\r\n/g, "\n").trim().split("\n").filter((l) => l.trim());
  const header = lines.shift().split(",").map((h) => h.trim());
  for (const col of COLUMNS) {
    if (!header.includes(col)) throw new Error(`CSV missing required column: ${col}`);
  }
  return lines.map((line) => {
    const cells = line.split(",").map((c) => c.trim());
    return Object.fromEntries(header.map((h, i) => [h, cells[i] ?? ""]));
  });
}

function certId(eventSlug, issueYear, email) {
  const hash = createHash("sha256").update(`${eventSlug}|${email}`).digest("hex").slice(0, 6);
  return `${eventSlug}-${issueYear}-${hash}`;
}

async function rowToCert(row) {
  const id = certId(row.eventSlug, row.issueYear, row.email);
  const qr = await QRCode.toDataURL(`${SITE_URL}/cert/${id}`, { margin: 1, scale: 4 });
  return {
    // email is intentionally NOT emitted — it's only used above to derive the
    // ID hash. Keeping it out of index.ts avoids shipping PII to the client.
    certId: id,
    name: row.name,
    event: row.event,
    eventSlug: row.eventSlug,
    issueYear: Number(row.issueYear),
    date: row.date,
    templateId: row.templateId,
    qr,
  };
}

async function main() {
  const inputs = process.argv.slice(2);
  if (!inputs.length) {
    console.error("usage: bun run scripts/generate-certificates.mjs <input.csv> [...]");
    process.exit(1);
  }

  const rows = inputs.flatMap((f) => parseCsv(readFileSync(f, "utf8")));
  const certs = await Promise.all(rows.map(rowToCert));

  // Last write wins on duplicate IDs (same person re-listed) — dedupe by certId.
  const byId = new Map(certs.map((c) => [c.certId, c]));
  const unique = [...byId.values()];

  const body = `// AUTO-GENERATED by scripts/generate-certificates.mjs — do not edit by hand.
import type { Certificate } from "./types";

export const CERTIFICATES: Certificate[] = ${JSON.stringify(unique, null, 2)};

const BY_ID = new Map(CERTIFICATES.map((c) => [c.certId, c]));

export const getCertificateById = (id: string): Certificate | undefined =>
  BY_ID.get(id.trim());

export const getCertIdStaticParams = (): { certId: string }[] =>
  CERTIFICATES.map((c) => ({ certId: c.certId }));

export type { Certificate } from "./types";
`;

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, body);
  console.log(`Wrote ${unique.length} certificate(s) -> ${OUT}`);
}

// ponytail: self-check — same input row must yield the same ID across runs.
function selfCheck() {
  const a = certId("linux-101", "2026", "sajiya@example.com");
  const b = certId("linux-101", "2026", "sajiya@example.com");
  if (a !== b) throw new Error("certId not deterministic");
  if (certId("linux-101", "2026", "other@example.com") === a) throw new Error("certId collision");
  if (!/^linux-101-2026-[0-9a-f]{6}$/.test(a)) throw new Error(`unexpected id shape: ${a}`);
}

selfCheck();
main();
